#!/usr/bin/env bash
# Set up a jamovi-src checkout for testing modules in Docker, without changing
# jamovi's own files or image:
#
#  - writes docker-compose.override.yaml, which docker compose loads on top of
#    docker-compose.yaml. It tags the image by the checkout's version (upstream's
#    compose file still says 28.1 at 28.4), and mounts a volume at /root/.jamovi,
#    where jamovi keeps user-installed modules and settings.json (language, ...),
#    so both survive restarts, down/up, image rebuilds and reboots
#  - lists that file in .git/info/exclude, so the checkout stays an exact copy
#    of upstream
#  - installs the compiler's npm dependencies, which tools/install.sh docker
#    runs on this machine
#
#   bash scripts/docker-setup.sh /path/to/jamovi-src
#
# Rerun after updating the checkout, to follow its version. Then:
#   docker-compose --profile main build jamovi
#   docker-compose --profile main up -d
#   bash tools/install.sh docker          (in each module repo)
# 'docker-compose --profile main down -v' would delete the volume with the modules.
set -euo pipefail

SRC="$(cd "${1:?usage: docker-setup.sh /path/to/jamovi-src}" && pwd)"
[ -f "$SRC/docker-compose.yaml" ] && [ -f "$SRC/version" ] || {
  echo "error: $SRC is not a jamovi checkout" >&2; exit 1; }
TAG="$(cut -d. -f1,2 "$SRC/version")"

cat > "$SRC/docker-compose.override.yaml" <<EOF
# Generated by jamovi-skill scripts/docker-setup.sh; local only (listed in
# .git/info/exclude). Rerun that script after updating this checkout.
#
# 1. image: upstream still labels the image jamovi/jamovi:28.1, so building
#    as-is would overwrite and mislabel an older local image.
# 2. jamovi-home: jamovi keeps user-installed modules and settings.json in
#    \$HOME/.jamovi (/root/.jamovi); a volume keeps them across down/up.
services:
  jamovi:
    image: jamovi/jamovi:$TAG
    volumes:
      - jamovi-home:/root/.jamovi
  jamovi-dev:
    image: jamovi/jamovi:$TAG
    volumes:
      - jamovi-home:/root/.jamovi
  test:
    image: jamovi/jamovi:$TAG

volumes:
  jamovi-home:
EOF
echo ">> wrote $SRC/docker-compose.override.yaml (image jamovi/jamovi:$TAG)"

EXCLUDE="$(git -C "$SRC" rev-parse --absolute-git-dir)/info/exclude"
grep -qx 'docker-compose.override.yaml' "$EXCLUDE" 2>/dev/null \
  || echo 'docker-compose.override.yaml' >> "$EXCLUDE"

if [ ! -d "$SRC/jamovi-compiler/node_modules" ]; then
  echo ">> installing the compiler's npm dependencies"
  ( cd "$SRC/jamovi-compiler" && npm install --no-audit --no-fund >/dev/null )
fi
echo ">> done"
